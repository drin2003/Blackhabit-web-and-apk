function normalizeSizeBH($size)
{
    $size = strtolower(trim((string)$size));

    if ($size === 'large' || $size === 'l') {
        return 'large';
    }

    return 'regular';
}

function displaySizeBH($size)
{
    return normalizeSizeBH($size) === 'large'
        ? 'Large'
        : 'Regular';
}

function jsonErrorBH($message, $extra = [])
{
    echo json_encode(
        array_merge(
            [
                "success" => false,
                "message" => $message
            ],
            $extra
        ),
        JSON_UNESCAPED_UNICODE |
        JSON_UNESCAPED_SLASHES
    );

    exit;
}


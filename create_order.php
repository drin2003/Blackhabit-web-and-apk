// ==========================================================
// VALIDATE ALL ITEMS BEFORE CREATING ORDER
// ==========================================================
//
// IMPORTANT:
// We validate FIRST.
// Only after every item passes validation do we INSERT
// the order.
//
// This prevents an unavailable product from creating

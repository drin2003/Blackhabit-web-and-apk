function tableExistsBH($conn, $table)
{
    $table = mysqli_real_escape_string($conn, $table);

    $result = mysqli_query(
        $conn,
        "SHOW TABLES LIKE '$table'"
    );

    return $result && mysqli_num_rows($result) > 0;
}

function columnExistsBH($conn, $table, $column)
{
    if (!tableExistsBH($conn, $table)) {
        return false;
    }

    $table = mysqli_real_escape_string($conn, $table);
    $column = mysqli_real_escape_string($conn, $column);

    $result = mysqli_query(
        $conn,
        "SHOW COLUMNS FROM `$table` LIKE '$column'"
    );

    return $result && mysqli_num_rows($result) > 0;
}

function findColumnBH($conn, $table, $columns)
{
    foreach ($columns as $column) {
        if (columnExistsBH($conn, $table, $column)) {
            return $column;
        }
    }

    return null;
}

function qtyBH($value)
{
    $value = (float)$value;

    if ($value < 0) {
        return 0;
    }

    return $value;
}

// Maximum quantity allowed for one product in one order.
